"""Regenerate browser DTOs and the JSON schema from the Pydantic source of truth."""

import json
from pathlib import Path

from classync_contracts.academic import (
    AcademicGenerationRequest,
    AcademicPeriodList,
    AcademicReadiness,
    AcademicSnapshot,
    CalendarWrite,
    PeriodCreate,
    RecordWrite,
)
from classync_contracts.publication import PublicationCommand, RoomRestriction
from classync_contracts.scheduling import (
    DraftDetail,
    DraftList,
    GenerationInput,
    GenerationResult,
    ReadinessResult,
    SaveDraftRequest,
    ValidationInput,
    ValidationResult,
)

ROOT = Path(__file__).resolve().parents[1]


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(v) for v in schema["anyOf"])
    if "oneOf" in schema:
        return " | ".join(ts(v) for v in schema["oneOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        required = schema.get("required", [])
        return (
            "{\n"
            + "\n".join(
                f"  {key}{'' if key in required else '?'}: {ts(value)};"
                for key, value in schema.get("properties", {}).items()
            )
            + "\n}"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


if __name__ == "__main__":
    definitions = {}
    schema_bundle = {}
    for model in (
        GenerationInput,
        GenerationResult,
        ReadinessResult,
        ValidationInput,
        ValidationResult,
        SaveDraftRequest,
        DraftDetail,
        DraftList,
        AcademicSnapshot,
    CalendarWrite,
        AcademicReadiness,
        AcademicGenerationRequest,
        AcademicPeriodList,
        PeriodCreate,
        RecordWrite,
        CalendarWrite,
        PublicationCommand,
        RoomRestriction,
    ):
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
        schema_bundle[model.__name__] = model.model_json_schema()
    output = "// Generated by scripts/export_scheduling_contracts.py. Do not edit.\n"
    output += (
        "\n\n".join(
            f"export type {name} = {ts(value)};" for name, value in sorted(definitions.items())
        )
        + "\n"
    )
    (ROOT / "packages/shared-types/src/scheduling.ts").write_text(output, encoding="utf-8")
    path = ROOT / "packages/api-contracts/schemas"
    path.mkdir(exist_ok=True)
    (path / "scheduling-v1.json").write_text(
        json.dumps(schema_bundle, indent=2) + "\n", encoding="utf-8"
    )
