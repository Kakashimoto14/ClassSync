"""Regenerate browser DTOs and the JSON schema from the Pydantic source of truth."""

import argparse
import json
from pathlib import Path

from classync_contracts.academic import (
    AcademicGenerationRequest,
    AcademicPeriodList,
    AcademicReadiness,
    AcademicSnapshot,
    CalendarWrite,
    PeriodCreate,
    RecordWrite,
)
from classync_contracts.publication import PublicationCommand, RoomRestriction
from classync_contracts.scheduling import (
    DraftDetail,
    DraftList,
    GenerationInput,
    GenerationResult,
    ReadinessResult,
    SaveDraftRequest,
    ValidationInput,
    ValidationResult,
)

ROOT = Path(__file__).resolve().parents[1]


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(v) for v in schema["anyOf"])
    if "oneOf" in schema:
        return " | ".join(ts(v) for v in schema["oneOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        required = schema.get("required", [])
        return (
            "{\n"
            + "\n".join(
                f"  {key}{'' if key in required else '?'}: {ts(value)};"
                for key, value in schema.get("properties", {}).items()
            )
            + "\n}"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


MODELS = (
    GenerationInput,
    GenerationResult,
    ReadinessResult,
    ValidationInput,
    ValidationResult,
    SaveDraftRequest,
    DraftDetail,
    DraftList,
    AcademicSnapshot,
    CalendarWrite,
    AcademicReadiness,
    AcademicGenerationRequest,
    AcademicPeriodList,
    PeriodCreate,
    RecordWrite,
    CalendarWrite,
    PublicationCommand,
    RoomRestriction,
)


def render_contracts():
    definitions = {}
    schema_bundle = {}
    for model in MODELS:
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
        schema_bundle[model.__name__] = model.model_json_schema()
    output = "// Generated by scripts/export_scheduling_contracts.py. Do not edit.\n"
    output += (
        "\n\n".join(
            f"export type {name} = {ts(value)};" for name, value in sorted(definitions.items())
        )
        + "\n"
    )
    return {
        Path("packages/shared-types/src/scheduling.ts"): output,
        Path("packages/api-contracts/schemas/scheduling-v1.json"):
            json.dumps(schema_bundle, indent=2) + "\n",
    }


def check_contracts(root=ROOT):
    drift = []
    for relative_path, expected in render_contracts().items():
        target = root / relative_path
        try:
            actual = target.read_text(encoding="utf-8")
        except FileNotFoundError:
            actual = None
        if actual != expected:
            drift.append(relative_path.as_posix())
    return drift


def write_contracts(root=ROOT):
    for relative_path, content in render_contracts().items():
        target = root / relative_path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="check generated files without modifying them"
    )
    args = parser.parse_args(argv)
    if not args.check:
        write_contracts()
        return 0
    drift = check_contracts()
    if drift:
        for path in drift:
            print(f"Contract drift: {path}")
        return 1
    print("Scheduling TypeScript and JSON schema contracts are in sync.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
